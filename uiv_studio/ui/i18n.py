def set_language(lang: str):
    global _lang
    _lang = "en" if lang == "en" else "it"


def language() -> str:
    return _lang


def tr(key: str, /, **fmt) -> str:
    pair = T.get(key)
    if pair is None:
        s = key
    else:
        s = pair[0] if _lang == "it" else pair[1]
    return s.format(**fmt) if fmt else s
